#!/usr/bin/env python3
"""Read-only owner DLL audit; normalized metadata, not original script dumps."""
import argparse, hashlib, re, struct, pathlib
BASE=0x22000000
SHA="568a0086fde607345adf31d7cfb2a5bf4e4efe9a86f416faa97076ddf9d97650"
BLOCKS=(("elite",0x22355a00,0x22355ac5),("ground",0x2235f800,0x22360781),("jet",0x22368700,0x22368c80))
def extract(b,activities):
    if hashlib.sha256(b).hexdigest()!=SHA: raise ValueError("wrong original server DLL")
    def word(x): return struct.unpack_from("<I",b,x-BASE)[0]
    def string(x):
        if not 0x223d2000<=x<0x224d6000: raise ValueError("not original rdata")
        return b[x-BASE:b.index(b"\0",x-BASE)].decode("ascii")
    names={}; scripts=[]
    for family,lo,hi in BLOCKS:
        for x in range(lo,hi):
            if b[x-BASE]!=0xe8: continue
            dest=(x+5+word(x+1))&0xffffffff
            if dest not in (0x2208c590,0x22042620): continue
            stores=[(y,word(y+4)) for y in range(x-48,x-7) if b[y-BASE:y-BASE+3]==b"\xc7\x44\x24"]
            if dest==0x2208c590:
                if len(stores)<2: raise ValueError("missing registration operands")
                names[family,string(stores[-2][1])]=stores[-1][1]
            else:
                if not stores: raise ValueError("missing script vector operand")
                scripts.append((family,stores[-1][1],x))
    for m in re.finditer(rb"(?:\x6a(.)|\x68(....))\x68(....)\xb9(....)\xe8(....)",b[0x1000:0x3d111a],re.S):
        end=BASE+0x1000+m.end()
        if (end+struct.unpack("<I",m[5])[0])&0xffffffff!=0x22073760: continue
        if struct.unpack("<I",m[4])[0] not in (0x225475dc,0x225475f4,0x2254760c): continue
        names["shared",string(struct.unpack("<I",m[3])[0])]=m[1][0] if m[1] else struct.unpack("<I",m[2])[0]
    # Match numeric activity seed entries obtained from original 220e7040 initializer.
    private={"ACT_COMBINE_BUGBAIT":"p2","ACT_COMBINE_AR2_ALTFIRE":"p3","ACT_GRUNT_SHOT_IN_HELMET":"p5"}
    def lookup(family,name):
        for f in (family,"ground","shared"):
            if (f,name) in names:return names[f,name]
        raise ValueError("unresolved symbol: "+name)
    rows=[]
    for family,ptr,call in scripts:
        tok=string(ptr).split()
        if tok[0]!="Schedule" or tok[2]!="Tasks": raise ValueError("unexpected syntax")
        name=tok[1]; stop=tok.index("Interrupts"); tasks=tok[3:stop]
        if len(tasks)%2:raise ValueError("task arguments")
        vals=[]
        for t,a in zip(tasks[::2],tasks[1::2]):
            if a.startswith("SCHEDULE:"):a="s"+str(lookup(family,a[9:]))
            elif a.startswith("ACTIVITY:"):
                n=a[9:];a=private[n] if n in private else "a"+str(activities[n])
            elif a=="MEMORY:INCOVER":a="m2"
            elif a=="GOAL:TARGET":a="g1"
            elif a=="DMG_BURN":a="d0"
            else:float(a)
            vals.append(str(lookup(family,t))+":"+a)
        row=" ".join([family,str(lookup(family,name)),name,f"{ptr:08x}",f"{call:08x}",",".join(vals),",".join(str(lookup(family,c)) for c in tok[stop+1:])]).rstrip()
        rows.append(row)
    return "\n".join(rows)+"\n"
def main():
    p=argparse.ArgumentParser();p.add_argument("--server",type=pathlib.Path,required=True);p.add_argument("--activity-tsv",type=pathlib.Path,required=True);p.add_argument("--catalog",type=pathlib.Path,default=pathlib.Path(__file__).with_name("grunt_schedule_catalog_phase1073.tsv"));a=p.parse_args()
    # TSV generated by the previously authenticated activity initializer audit.
    data=a.activity_tsv.read_bytes()
    if hashlib.sha256(data).hexdigest()!="1331c3f2bea2e829a22799fc91d3981eeca38507ed58a33229befd37284b985f":raise ValueError("activity seed hash")
    activities={name:int(id) for id,name in (line.split("\t",1) for line in data.decode().splitlines())}
    result=extract(a.server.read_bytes(),activities)
    if result!=a.catalog.read_text():raise ValueError("catalog differs from authenticated extraction")
    print("PASS: 46 original registered schedules; normalized task/interrupt data matches")
if __name__=="__main__":main()
